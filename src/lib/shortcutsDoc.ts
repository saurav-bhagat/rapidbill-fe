import { comboLabels } from './hotkeys'
import { SHORTCUTS, type ShortcutDoc } from './shortcuts'

const fmt = (combo: string, mac: boolean) => comboLabels(combo, mac).join(mac ? '' : '+')
const keys = (s: ShortcutDoc, mac: boolean) => [s.combo, ...(s.alt ?? [])].map((c) => `\`${fmt(c, mac)}\``).join(' or ')
const WHERE: Record<ShortcutDoc['scope'], string> = { global: 'Anywhere', billing: 'Billing screen', list: 'Lists and Settings (not while typing in a field)', modal: 'Open dialog or drawer' }
const GROUPS: ShortcutDoc['group'][] = ['Navigate', 'Billing', 'Lists', 'Dialogs']

/** SHORTCUTS.md is generated from the same list the in-app overlay uses, so the two cannot drift. */
export function renderShortcutsMd(): string {
  const tables = GROUPS.map((g) => {
    const rows = SHORTCUTS.filter((s) => s.group === g).map((s) => `| ${keys(s, false)} | ${keys(s, true)} | ${WHERE[s.scope]} | ${s.description} |`)
    return `### ${g}\n\n| Windows / Linux | Mac | Where | Does |\n|---|---|---|---|\n${rows.join('\n')}\n`
  }).join('\n')

  return `<!-- Generated by \`npm run docs:shortcuts\` from src/lib/shortcuts.ts. Do not edit by hand. -->
# RapidBill keyboard shortcuts

Press \`?\` anywhere in the app for this list. **Ctrl** on Windows/Linux is **⌘ Cmd** on Mac. Every action also works with the mouse.

## The fast path: issuing stock without touching the mouse

1. \`Alt+K\` opens a new Stock Issue. The voucher number and today's date are already filled in.
2. The cursor is on **Party**. Type to search, \`Enter\` to pick (or just \`Enter\` for cash / counter).
3. Type part of an item name, code or batch, \`↑ ↓\` to choose, \`Enter\`.
4. Type **Qty**, \`Enter\`. Check **Rate**, \`Enter\`. Type **Disc %**, \`Enter\`. The row is committed and the cursor drops to the next row.
5. Missing item? Press \`F2\` to add it without leaving the bill.
6. \`F4\` for a bill-level discount (\`5%\` or \`250\`).
7. \`Ctrl+S\` to save and preview the invoice, or \`Ctrl+Enter\` to save and start the next customer.

## All shortcuts

${tables}
## Platform notes

- **Mac:** Alt shortcuts are matched on the physical key, so \`⌥K\` works even though Option+K types a symbol. Cmd and Ctrl are interchangeable.
- **Letter shortcuts in lists** (\`N\`, \`E\`, \`A\`, \`I\`, \`P\`, \`C\`, \`/\`) only fire when the cursor is not inside a text box, so they never interfere with typing.
- **While a dialog or drawer is open**, only the dialog's own shortcuts work. Global and billing shortcuts are paused so a stray key cannot change the page behind it.

## Browser limits

Browsers reserve a few keys for themselves.

- **\`Ctrl+W\` cannot be relied on.** Chrome, Edge, Firefox and Safari close the tab before the page sees the key. RapidBill listens for it anyway, but use \`Ctrl+S\` or \`F10\` to save and print. If the tab does close on an unsaved voucher the browser asks before leaving.
- \`Ctrl+D\` (Duplicate in the Register) normally bookmarks the page. RapidBill overrides it there; if your browser still shows the bookmark bar, use the **Duplicate** button.
- \`Ctrl+P\` is overridden in the invoice preview so it prints the invoice, not the app.
- Function keys can be captured by the OS on some laptops (brightness, volume). Hold **Fn** or change the keyboard setting if \`F2\`, \`F4\` or \`F10\` seem to do nothing.
`
}
